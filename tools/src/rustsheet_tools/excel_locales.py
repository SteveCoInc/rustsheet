"""Generate the engine's locale name tables from Excel's own answers (T-3666).

Excel prints a `[$-...]` locale tag's month, day and day-half names from Windows' locale data,
which is neither CLDR nor stable across products, so the tables are read off Excel:

- probes/t3666-lcid-locale-map: which LCIDs (languages 0x01-0xFF x sublanguages 0-63) have a locale;
- probes/t3666-locale-names: the names under each of them (and 0x400, 0x800, 0xC00);
- probes/t3666-locale-tag-names: the names under every BCP-47 tag of [MS-LCID] and CLDR.

`ms_lcid_tags.tsv` (from [MS-LCID] 2.2) gives the LCID a tag names, so a tag keeps its LCID's
calendar rules (`[$-ja-JP]g`). The output, read by `locale::excel_date_names` and
`formatter::table_calendars`:

- crates/rustsheet-engine/src/locale/`excel_names.tsv`: one name set per line (12 `mmm`, 12
  `mmmm`, 7 `ddd`, 7 `dddd`, AM, PM), numbered from 0 in file order, with `\\`, `\t` and `\n`
  escaped;
- `excel_lcids.tsv`: LCID (hex) and name-set number;
- `excel_tags.tsv`: tag, its LCID (hex, or `-` for none) and name-set number;
- `excel_calendars.tsv`: the names of each calendar digit under each LCID ([`calendar_rows`]);
- crates/rustsheet-engine/src/formatter/`persian_years.txt` and `um_al_qura_months.txt`: the
  Persian and Um al-Qura calendars ([`write_persian_years`], [`write_um_al_qura_months`]).

Run `uv run rustsheet-excel-locales` from tools/ after refilling one of the probes.
"""

from __future__ import annotations

import json
import re
import sys
from collections.abc import Callable
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
CASES = ROOT / "eval" / "suites" / "probes" / "cases"
OUT = ROOT / "crates" / "rustsheet-engine" / "src" / "locale"
MS_LCID = Path(__file__).resolve().parent / "ms_lcid_tags.tsv"
SEP = "\x1f"
# What a tag or LCID with no locale prints in the map probe: `A/P` as written, en-US names.
NO_LOCALE = "P January"
# The fields of a probe row after its key: 38 names (12 `mmm`, 12 `mmmm`, 7 `ddd`, 7 `dddd`), the
# two day halves, `A/P` of 0.75, `mmmm` of March and `yyyy-mm-dd` of 45000.
NAMES = slice(1, 39)
AM, PM, AP, MARCH, YMD = 39, 40, 41, 15, 42
HEADER = (
    "# Generated by `uv run rustsheet-excel-locales` (tools/src/rustsheet_tools/excel_locales.py) from\n"
    "# Excel's answers in probes/t3666-* and t4061-*; do not edit by hand.\n"
)


def oracle_rows(case: str, sep: str = SEP) -> list[list[str]]:
    sheet = json.loads((CASES / f"{case}.oracle.json").read_text(encoding="utf-8"))["sheets"]["S"]
    return [cell["v"].split(sep) for cell in sheet.values() if cell["t"] == "s"]


def lcids_with_locale() -> set[int]:
    found = {0x400, 0x800, 0xC00}
    sheet = json.loads((CASES / "t3666-lcid-locale-map.oracle.json").read_text(encoding="utf-8"))
    for key, cell in sheet["sheets"]["S"].items():
        language = int(key[1:])
        for sublanguage, text in enumerate(cell["v"].split("~")):
            if text != NO_LOCALE:
                found.add(sublanguage << 10 | language)
    return found


def extended_hex(tag: str) -> int | None:
    """`locale_tag::extended_hex`: Excel's reading of a short tag as hex digits."""
    if not tag or not tag.isascii():
        return None
    value = 0
    for c in tag:
        if c >= "a":
            digit = ord(c) - ord("a") + 10
        elif "A" <= c <= "Z":
            digit = ord(c) - ord("A") + 10
        else:
            digit = ord(c) - ord("0")
        value = (value * 16 + digit) & 0xFFFFFFFF
    return value


def name_set(row: list[str]) -> tuple[str, ...]:
    return (*row[NAMES], row[AM], row[PM])


def escape(name: str) -> str:
    """A name as a table field: Excel's names may hold tabs (0xF803's `mmmm`)."""
    return name.replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n")


# The no-locale LCID whose calendar names stand for every LCID with no locale.
NO_LOCALE_LCID = 0xD001
# Calendar digits whose names the digest probe covers.
CALENDAR_DIGITS = range(1, 0x18)
HEBREW = 8
FORMATTER = ROOT / "crates" / "rustsheet-engine" / "src" / "formatter"


def calendar_rows(
    by_lcid: dict[int, tuple[str, ...]],
    number: Callable[[tuple[str, ...]], int],
    sets: dict[tuple[str, ...], int],
) -> list[str]:
    """`excel_calendars.tsv`: for each calendar digit, `digit<TAB>key<TAB>names[<TAB>13 leap months]`.

    The key is `*` (the digit's default, its commonest names over the LCIDs with a locale), `-` (an
    LCID with no locale) or an LCID in hex whose names differ from the default; names is a name-set
    number, `=` for the LCID's own names or `-` for those of an LCID with no locale (whose months
    go by Gregorian number). Hebrew rows add the 13 month names of a leap year (the 12 of the name
    set are a common year's). The names
    of every LCID under the digits whose names vary come from probes/t4061-calendar-names-all; the
    other digits print one set under every LCID (probes/t4061-calendar-names-digest), read from
    probes/t4061-calendar-names-full.
    """
    exact = probed_calendar_names("t4061-calendar-names-all")
    representative = probed_calendar_names("t4061-calendar-names-full")
    lcids = sorted({lcid for _, lcid in exact})
    lines = []
    for digit in CALENDAR_DIGITS:

        def names_of(lcid: int, digit: int = digit) -> tuple[tuple[str, ...], list[str]]:
            if (digit, lcid) in exact:
                return exact[(digit, lcid)]
            return next(v for (d, _), v in representative.items() if d == digit)

        held = {lcid: calendar_value(names_of(lcid), by_lcid.get(lcid), number) for lcid in lcids}
        counts: dict[str, int] = {}
        for lcid, value in held.items():
            if lcid in by_lcid:
                counts[value] = counts.get(value, 0) + 1
        default = max(counts, key=lambda value: counts[value])
        no_locale = held[NO_LOCALE_LCID]
        lines.append(f"{digit:X}\t*\t{default}")
        lines.append(f"{digit:X}\t-\t{no_locale}")
        default_names = resolved_names(default, None, sets)
        for lcid in lcids:
            base = default if lcid in by_lcid else no_locale
            # A row that prints what the default does adds nothing (`=` where the LCID's own
            # names are the default set's).
            same = lcid in by_lcid and resolved_names(held[lcid], by_lcid[lcid], sets) == default_names
            if lcid != NO_LOCALE_LCID and held[lcid] != base and not same:
                # `-`: as under an LCID with no locale (`[$-80CEB]`, whose own names differ).
                value = "-" if held[lcid] == no_locale else held[lcid]
                lines.append(f"{digit:X}\t{lcid:X}\t{value}")
    return lines


def resolved_names(
    value: str, own: tuple[str, ...] | None, sets: dict[tuple[str, ...], int]
) -> tuple[str, ...] | str:
    """The names a row value prints (its leap months included), for comparing rows."""
    head, _, leap = value.partition("\t")
    if head == "=" and own is not None:
        return (*own[:38], leap)
    if head.isdigit():
        names = next(n for n, i in sets.items() if i == int(head))
        return (*names[:38], leap)
    return value


def calendar_value(
    probed: tuple[tuple[str, ...], list[str]],
    own: tuple[str, ...] | None,
    number: Callable[[tuple[str, ...]], int],
) -> str:
    """A row's `names[<TAB>leap months]`: `=` when the calendar prints the LCID's own names."""
    names, leap = probed
    if not leap and own is not None and names == own[:38]:
        return "="
    return "\t".join([str(number((*names, "AM", "PM"))), *(escape(x) for x in leap)])


def probed_calendar_names(case: str) -> dict[tuple[int, int], tuple[tuple[str, ...], list[str]]]:
    """The names of each (digit, LCID) of a probe whose cells join with "~" a label, then
    `yyyy|m|mmm|mmmm[|ddd|dddd]` (or `ddd|dddd`) of `TEXT(DATE(...),"[$-dLLLL]...")` calls, in
    order: 12 `mmm` and 12 `mmmm` by month (Hebrew: of the common year 5783), 7 `ddd` and 7
    `dddd` by weekday from Sunday, and for Hebrew the 13 `mmmm` of the leap year 5784."""
    cells = json.loads((CASES / f"{case}.case.json").read_text(encoding="utf-8"))["sheets"][0]["cells"]
    sheet = json.loads((CASES / f"{case}.oracle.json").read_text(encoding="utf-8"))["sheets"]["S"]
    samples: dict[tuple[int, int], list[tuple[date, list[str]]]] = {}
    for key, formula in cells.items():
        calls = re.findall(
            r'TEXT\(DATE\((\d+),(\d+),(\d+)\),"\[\$-([0-9A-F]+?)([0-9A-F]{4})\]([^"]*)"\)', formula
        )
        results = sheet[key]["v"].split("~")[1:]
        for (year, month, day, digit, lcid, code), text in zip(calls, results, strict=True):
            fields = dict(zip(code.split("|"), text.split("|"), strict=True))
            when = date(int(year), int(month), int(day))
            samples.setdefault((int(digit, 16), int(lcid, 16)), []).append(
                (when, [fields.get(f, "") for f in ("yyyy", "m", "mmm", "mmmm", "ddd", "dddd")])
            )
    return {key: names_from_samples(key[0], rows) for key, rows in samples.items()}


def names_from_samples(digit: int, rows: list[tuple[date, list[str]]]) -> tuple[tuple[str, ...], list[str]]:
    short: dict[int, str] = {}
    long: dict[int, str] = {}
    leap: dict[int, str] = {}
    day_short: dict[int, str] = {}
    day_long: dict[int, str] = {}
    for when, (year, month, mmm, mmmm, ddd, dddd) in rows:
        if month:
            m = int(month)
            if digit == HEBREW and year == "5784":
                leap.setdefault(m, mmmm)
            elif m <= 12:
                short.setdefault(m, mmm)
                long.setdefault(m, mmmm)
        if ddd or dddd:
            weekday = (when.weekday() + 1) % 7
            day_short.setdefault(weekday, ddd)
            day_long.setdefault(weekday, dddd)
    names = (
        *(short[m] for m in range(1, 13)),
        *(long[m] for m in range(1, 13)),
        *(day_short[w] for w in range(7)),
        *(day_long[w] for w in range(7)),
    )
    return names, [leap[m] for m in range(1, 14)] if digit == HEBREW else []


def first_day_columns(case: str) -> list[str]:
    sheet = json.loads((CASES / f"{case}.oracle.json").read_text(encoding="utf-8"))["sheets"]["S"]
    return [sheet[f"A{n}"]["v"] for n in range(1, len(sheet) + 1) if f"A{n}" in sheet]


def write_persian_years() -> None:
    """`formatter/persian_years.txt`: Excel's Persian calendar (digit 0x16) as the length of every
    year 1278-9378, read off probes/t4061-persian-new-years (the Persian date of March 28, always in
    month 1, of every Gregorian year 1900-9999)."""
    starts: dict[int, date] = {}
    for n, cell in enumerate(first_day_columns("t4061-persian-new-years")):
        for i, text in enumerate(cell.split("~")):
            gregorian = 1900 + 100 * n + i
            _, month, day = (int(x) for x in text.split("-"))
            if month != 1:
                raise SystemExit(f"{gregorian}-03-28 is not in month 1: {text}")
            starts[gregorian - 621] = date(gregorian, 3, 28) - timedelta(days=day - 1)
    # 1900-01-01 is 1278-10-11 (probes/t4061-persian-and-hijri-variant C2), so 1278 began 286
    # days earlier.
    starts[1278] = date(1900, 1, 1) - timedelta(days=286)
    years = sorted(starts)
    bits = "".join("1" if (starts[y + 1] - starts[y]).days == 366 else "0" for y in years[:-1])
    lines = [f"{years[0] + i}\t{bits[i : i + 64]}" for i in range(0, len(bits), 64)]
    epoch = (starts[years[0]] - date(1899, 12, 30)).days
    (FORMATTER / "persian_years.txt").write_text(
        HEADER
        + f"# Year {years[0]} starts on day {epoch} (1899-12-30 is 0). Each line: a year, then one digit\n"
        + "# per year from it, 1 for a 366-day year. Months 1-6 have 31 days, 7-11 30, 12 the rest.\n"
        + f"{years[0]}\t{epoch}\n"
        + "".join(f"{x}\n" for x in lines),
        encoding="utf-8",
    )


def write_um_al_qura_months() -> None:
    """`formatter/um_al_qura_months.txt`: Excel's Um al-Qura calendar (digit 0x17) as the length of
    every month of its table, read off probes/t4061-umalqura-months (the 1st and 16th of every
    Gregorian month 1900-2100). Outside the table Excel uses the tabular Hijri calendar of digit 6."""
    dates = [date(y, m, d) for y in range(1900, 2101) for m in range(1, 13) for d in (1, 16)]
    texts = "~".join(first_day_columns("t4061-umalqura-months")).split("~")
    starts: dict[tuple[int, int], date] = {}
    for gregorian, text in zip(dates, texts, strict=True):
        year, month, day = (int(x) for x in text.split("-"))
        starts[(year, month)] = gregorian - timedelta(days=day - 1)
    first, last = (1318, 1), (1501, 1)
    lines = []
    for year in range(first[0], last[0]):
        lengths = []
        for month in range(1, 13):
            following = (year, month + 1) if month < 12 else (year + 1, 1)
            lengths.append("1" if (starts[following] - starts[(year, month)]).days == 30 else "0")
        lines.append(f"{year}\t{''.join(lengths)}")
    epoch = (starts[first] - date(1899, 12, 30)).days
    (FORMATTER / "um_al_qura_months.txt").write_text(
        HEADER
        + f"# 1 Muharram {first[0]} is day {epoch} (1899-12-30 is 0). Each line: a year, then one digit per\n"
        + "# month, 1 for 30 days and 0 for 29. Before and after the table Excel's dates are digit 6's.\n"
        + f"{first[0]}\t{epoch}\n"
        + "".join(f"{x}\n" for x in lines),
        encoding="utf-8",
    )


def main() -> int:
    with_locale = lcids_with_locale()
    documented: dict[str, int] = {}
    for line in MS_LCID.read_text(encoding="utf-8").splitlines():
        if line and not line.startswith("#"):
            lcid, tag = line.split("\t")
            documented[tag.lower()] = int(lcid, 16)

    sets: dict[tuple[str, ...], int] = {}

    def number(names: tuple[str, ...]) -> int:
        return sets.setdefault(names, len(sets))

    by_lcid: dict[int, tuple[str, ...]] = {}
    for row in sorted(oracle_rows("t3666-locale-names"), key=lambda r: int(r[0])):
        if int(row[0]) in with_locale:
            by_lcid[int(row[0])] = name_set(row)

    tags: list[tuple[str, int | None, tuple[str, ...]]] = []
    for row in sorted(oracle_rows("t3666-locale-tag-names"), key=lambda r: r[0].lower()):
        tag, names = row[0], name_set(row)
        # A locale prints its own day halves for `A/P`; a tag that keeps "P" has none. Some of those
        # still print names, read as extended hex (`an-ES` is calendar digit B, Arabic names), and
        # so do tags with another calendar or digits (`tok-001`): leave them to that path.
        if row[AP] == "P" or row[YMD] != "2023-03-15":
            continue
        # An undocumented tag that reads as an LCID with the same names is that LCID (`[$-bgc]` is
        # 0xC0C, fr-CA), unless the tag spells that LCID's hex digits: then the tag wins and the
        # LCID has no locale of its own (`[$-CEB]` is Cebuano by its tag, `[$-0CEB]` and
        # `[$-80CEB]` have no locale; probes/t4061-calendars-without-locale C1:C24).
        value = extended_hex(tag)
        if (
            value is not None
            and documented.get(tag.lower()) is None
            and value >> 16 == 0
            and by_lcid.get(value & 0xFFFF) == names
            and f"{value:x}" != tag.lower()
        ):
            continue
        tags.append((tag, documented.get(tag.lower()), names))

    # A hex LCID that is really a tag (`[$-CA]` is Catalan by its tag "ca", 0xCA has no locale).
    tag_names = {tag.lower() for tag, _, _ in tags}
    lcid_rows = [(lcid, n) for lcid, n in by_lcid.items() if f"{lcid:x}" not in tag_names]

    lcid_lines = [f"{lcid:X}\t{number(names)}" for lcid, names in lcid_rows]
    tag_lines = [
        f"{tag}\t{'-' if lcid is None else f'{lcid:X}'}\t{number(names)}" for tag, lcid, names in tags
    ]
    mismatched = [
        tag for tag, lcid, names in tags if lcid is not None and lcid in by_lcid and by_lcid[lcid] != names
    ]
    (OUT / "excel_lcids.tsv").write_text(HEADER + "".join(f"{x}\n" for x in lcid_lines), encoding="utf-8")
    (OUT / "excel_tags.tsv").write_text(HEADER + "".join(f"{x}\n" for x in tag_lines), encoding="utf-8")
    calendar_lines = calendar_rows(by_lcid, number, sets)
    (OUT / "excel_calendars.tsv").write_text(
        HEADER + "".join(f"{x}\n" for x in calendar_lines), encoding="utf-8"
    )
    (OUT / "excel_names.tsv").write_text(
        HEADER + "".join("\t".join(map(escape, names)) + "\n" for names in sets), encoding="utf-8"
    )
    write_persian_years()
    write_um_al_qura_months()
    print(
        f"{len(sets)} name sets, {len(lcid_lines)} LCIDs, {len(tag_lines)} tags, {len(calendar_lines)} calendar rows"
    )
    if mismatched:
        print(f"tags whose names differ from their LCID's: {', '.join(mismatched)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
