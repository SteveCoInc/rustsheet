//! The usage-tier gates of decision 0355 item 3 on a run's eval cells, and the tier lock of item
//! 6 (SPEC-0037 design 6): [`LOCK_PATH`] holds each tier's met state, and a full gated `check`
//! fails when a tier written `met` is unmet.
//!
//! **Cells counted** ([`function_cells`]): the scored, non-deviation Excel cells of the probe
//! suites and Gate B's suites ([`counts_suite`]), each toward its formula's sole non-glue call
//! (decision 0118, [`sole_call`]) when every function it calls is in scope. Left out: the
//! decision 0134 exceptions, the pivot suites and GETPIVOTDATA (decision 0354). A cell with no sole
//! call counts toward no function, as decision 0118 item 6 says. Each counted cell is classed by
//! [`cell_envelope`], the one per-cell envelope test.
//!
//! **The bars** ([`Bars`]): foundational 100% right type pooled and at least 99.99% inside the
//! envelope pooled; expert at least 99.9% pooled on both and at least 99% of each function's cells
//! on both. A function with no counted cell meets its bars; coverage gates it elsewhere.
//!
//! The gated run covers only the vendored gated suites, so `check` computes the tiers on those
//! cells and says so: the full report's tiers (report.json `usage_gates`) are the exit measure,
//! and [`function_cells`] and [`tiers`] are the one computation for both.

