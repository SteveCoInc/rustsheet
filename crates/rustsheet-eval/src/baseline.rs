//! The no-regression ratchet ("known failures" baseline).
//!
//! `eval/baseline/<suite>.txt` records, for every case, how many cells it
//! checks, plus the exact list of items that are *known to fail*. The gate is:
//!
//! * any failing item that is **not** listed, in a case whose checked-cell count is
//!   unchanged, is a **regression** → CI fails;
//! * failing items in new or changed cases are **new coverage** → allowed, but must be
//!   recorded with `rustsheet-eval update-baseline`;
//! * listed items that now pass are **fixes** → ratchet them with `update-baseline`.
//! * a case missing from the baseline, even one that passes, is a **new case** → its
//!   checked-cell count must be recorded with `update-baseline`.
//!
//! The known-failure list doubles as the compatibility to-do list.
//!
//! Displayed text (decision 0068) is gated the same way on its own lines (decision 0070):
//! `TC<TAB>case<TAB>n` counts a case's scored text cells and `TF<TAB>case<TAB>Sheet!A1` lists
//! a known text failure, with the same regression, new-coverage and fix rules.
//!
//! A pivot's layout is gated the same way where the case compares it in full, location and
//! saved `rowItems`/`colItems` (an engine-export case, T-4944): `LC<TAB>case<TAB>n` counts the
//! case's sidecar pivots and `LF<TAB>case<TAB>Sheet!Pivot` lists a pivot whose layout is not
//! Excel's, whatever its [`crate::pivot_scoring::LayoutVerdict`]: a location fixed to reveal
//! wrong lines is no new failure. Any case whose pivots a saved package is compared for (the
//! round-trip goldens of SPEC-0033 X3, T-4180) can fill the same lines. The file header is left
//! as it was, so the new kinds rewrite only the baselines that hold them.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::Path;

use anyhow::{Context, Result};

use crate::runner::{CaseResult, CaseStatus};
use crate::suite::BaselineMode;

const HEADER: &str = "# RustSheet eval baseline (known failures). Generated by `rustsheet-eval update-baseline`;\n\
# never edit by hand. `C<TAB>case<TAB>checked-cells` lists every case; `F<TAB>case<TAB>item` lists\n\
# known failures. Removing an F line = a fix. Adding an F line to an unchanged case = a regression\n\
# and requires --allow-regressions plus a justification in the PR (docs/process/quality-gates.md).\n\
# `TC` and `TF` lines do the same for displayed text (decision 0070).\n";

#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Baseline {
    /// case id → number of checked cells.
    pub checked: BTreeMap<String, usize>,
    /// (case id, item) known to fail. Item is `Sheet!A1`, `*` (whole case) or `!status`.
    pub failing: BTreeSet<(String, String)>,
    /// case id → number of scored displayed-text cells (cases with none are absent).
    pub text_checked: BTreeMap<String, usize>,
    /// (case id, `Sheet!A1`) whose displayed text is known to fail.
    pub text_failing: BTreeSet<(String, String)>,
    /// case id → number of sidecar pivots whose layout is compared in full (cases with none are
    /// absent).
    pub layout_checked: BTreeMap<String, usize>,
    /// (case id, `Sheet!Pivot`) whose layout is known not to be Excel's.
    pub layout_failing: BTreeSet<(String, String)>,
}

impl Baseline {
    /// Builds the baseline describing `results`.
    #[must_use]
    pub fn from_results(mode: BaselineMode, results: &[&CaseResult]) -> Baseline {
        let mut b = Baseline::default();
        if mode == BaselineMode::None {
            return b;
        }
        for r in results {
            if r.status == CaseStatus::Pending {
                continue;
            }
            b.checked.insert(r.id.clone(), r.checked);
            // Text is gated per cell whatever the value mode (decision 0070).
            if !r.text.is_empty() {
                b.text_checked.insert(r.id.clone(), r.text.len());
                for t in r.text.iter().filter(|t| !t.pass) {
                    b.text_failing
                        .insert((r.id.clone(), format!("{}!{}", t.sheet, t.cell)));
                }
            }
            // So is a fully compared pivot layout, whatever the value mode (T-4944).
            if let Some(n) = r.layout_checked.filter(|n| *n > 0) {
                b.layout_checked.insert(r.id.clone(), n);
                for p in &r.pivot_layout {
                    b.layout_failing
                        .insert((r.id.clone(), format!("{}!{}", p.sheet, p.name)));
                }
            }
            match r.status {
                CaseStatus::Pass | CaseStatus::Pending => {}
                CaseStatus::Fail if mode == BaselineMode::Cells => {
                    for c in r.cells.iter().filter(|c| c.verdict.is_failure()) {
                        b.failing.insert((r.id.clone(), c.key()));
                    }
                }
                CaseStatus::Fail => {
                    b.failing.insert((r.id.clone(), "*".into()));
                }
                other => {
                    b.failing.insert((r.id.clone(), format!("!{other:?}")));
                }
            }
        }
        b
    }

    /// Reads a baseline file; a missing file is an empty baseline.
    ///
    /// # Errors
    /// Fails if the file exists but cannot be read or parsed.
    pub fn read(path: &Path) -> Result<Baseline> {
        let mut b = Baseline::default();
        if !path.exists() {
            return Ok(b);
        }
        let text = std::fs::read_to_string(path).with_context(|| path.display().to_string())?;
        for (n, line) in text.lines().enumerate() {
            if line.starts_with('#') || line.trim().is_empty() {
                continue;
            }
            let mut parts = line.splitn(3, '\t');
            let count = |cells: &str| -> Result<usize> {
                cells
                    .parse()
                    .with_context(|| format!("{}:{}: bad count", path.display(), n + 1))
            };
            match (parts.next(), parts.next(), parts.next()) {
                (Some("C"), Some(case), Some(cells)) => {
                    b.checked.insert(case.to_string(), count(cells)?);
                }
                (Some("F"), Some(case), Some(item)) => {
                    b.failing.insert((case.to_string(), item.to_string()));
                }
                (Some("TC"), Some(case), Some(cells)) => {
                    b.text_checked.insert(case.to_string(), count(cells)?);
                }
                (Some("TF"), Some(case), Some(item)) => {
                    b.text_failing.insert((case.to_string(), item.to_string()));
                }
                (Some("LC"), Some(case), Some(pivots)) => {
                    b.layout_checked.insert(case.to_string(), count(pivots)?);
                }
                (Some("LF"), Some(case), Some(item)) => {
                    b.layout_failing
                        .insert((case.to_string(), item.to_string()));
                }
                _ => anyhow::bail!("{}:{}: malformed line", path.display(), n + 1),
            }
        }
        Ok(b)
    }

    /// Writes the baseline deterministically.
    ///
    /// # Errors
    /// Fails if the file cannot be written.
    pub fn write(&self, path: &Path) -> Result<()> {
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        let mut out = String::from(HEADER);
        for (case, count) in &self.checked {
            let _ = writeln!(out, "C\t{case}\t{count}");
        }
        for (case, item) in &self.failing {
            let _ = writeln!(out, "F\t{case}\t{item}");
        }
        for (case, count) in &self.text_checked {
            let _ = writeln!(out, "TC\t{case}\t{count}");
        }
        for (case, item) in &self.text_failing {
            let _ = writeln!(out, "TF\t{case}\t{item}");
        }
        for (case, count) in &self.layout_checked {
            let _ = writeln!(out, "LC\t{case}\t{count}");
        }
        for (case, item) in &self.layout_failing {
            let _ = writeln!(out, "LF\t{case}\t{item}");
        }
        std::fs::write(path, out).with_context(|| path.display().to_string())
    }
}

#[derive(Debug, Default)]
pub struct Delta {
    /// Newly failing items in cases whose checked-cell count did not change.
    pub regressions: Vec<String>,
    /// Failing items in new or changed cases (allowed; must be recorded).
    pub new_failures: Vec<String>,
    /// Previously failing items that now pass.
    pub fixed: Vec<String>,
    /// Cases present in the baseline but absent now.
    pub removed_cases: Vec<String>,
    /// Cases absent from the baseline but run now, passing or not: their `C` line must be
    /// recorded (docs/process/quality-gates.md, T-1059).
    pub new_cases: Vec<String>,
}

impl Delta {
    /// Whether the baseline file would change.
    #[must_use]
    pub fn is_dirty(&self) -> bool {
        !(self.regressions.is_empty()
            && self.new_failures.is_empty()
            && self.fixed.is_empty()
            && self.removed_cases.is_empty()
            && self.new_cases.is_empty())
    }
}

/// Compares the committed baseline with the current run: values, then displayed text, whose
/// labels carry a `text ` prefix on the item (decision 0070), then pivot layouts, `layout `
/// (T-4944).
#[must_use]
pub fn diff(old: &Baseline, new: &Baseline) -> Delta {
    let mut d = Delta::default();
    diff_items(
        (&old.checked, &old.failing),
        (&new.checked, &new.failing),
        "",
        &mut d,
    );
    diff_items(
        (&old.text_checked, &old.text_failing),
        (&new.text_checked, &new.text_failing),
        "text ",
        &mut d,
    );
    diff_items(
        (&old.layout_checked, &old.layout_failing),
        (&new.layout_checked, &new.layout_failing),
        "layout ",
        &mut d,
    );
    d
}

type Items<'a> = (&'a BTreeMap<String, usize>, &'a BTreeSet<(String, String)>);

/// One ratchet over a (checked count, failing items) pair; `prefix` marks the items' labels.
fn diff_items(
    (old_checked, old_failing): Items<'_>,
    (new_checked, new_failing): Items<'_>,
    prefix: &str,
    d: &mut Delta,
) {
    for (case, item) in new_failing.difference(old_failing) {
        let label = format!("{case}\t{prefix}{item}");
        if old_checked.get(case) == new_checked.get(case) && old_checked.contains_key(case) {
            d.regressions.push(label);
        } else {
            d.new_failures.push(label);
        }
    }
    for (case, item) in old_failing.difference(new_failing) {
        if new_checked.contains_key(case) {
            d.fixed.push(format!("{case}\t{prefix}{item}"));
        }
    }
    for case in old_checked.keys() {
        if !new_checked.contains_key(case) {
            d.removed_cases.push(format!("{prefix}{case}"));
        }
    }
    for case in new_checked.keys() {
        if !old_checked.contains_key(case) {
            d.new_cases.push(format!("{prefix}{case}"));
        }
    }
    d.new_failures.extend(
        new_checked
            .iter()
            .filter(|(c, n)| old_checked.get(*c).is_some_and(|o| o != *n))
            .map(|(c, n)| format!("{c}\t({prefix}checked cells changed to {n})")),
    );
}

#[cfg(test)]
mod tests {
    use super::*;

    fn b(checked: &[(&str, usize)], failing: &[(&str, &str)]) -> Baseline {
        Baseline {
            checked: checked
                .iter()
                .map(|(c, n)| ((*c).to_string(), *n))
                .collect(),
            failing: failing
                .iter()
                .map(|(c, i)| ((*c).to_string(), (*i).to_string()))
                .collect(),
            ..Baseline::default()
        }
    }

    /// `base` with displayed-text counts and failures.
    fn with_text(base: Baseline, checked: &[(&str, usize)], failing: &[(&str, &str)]) -> Baseline {
        Baseline {
            text_checked: checked
                .iter()
                .map(|(c, n)| ((*c).to_string(), *n))
                .collect(),
            text_failing: failing
                .iter()
                .map(|(c, i)| ((*c).to_string(), (*i).to_string()))
                .collect(),
            ..base
        }
    }

    #[test]
    fn text_cells_ratchet_like_values() {
        // A text cell that passed in an unchanged case and now fails is a regression even when
        // every value still passes (decision 0070).
        let old = with_text(b(&[("a", 3)], &[]), &[("a", 2)], &[("a", "S!A1")]);
        let new = with_text(b(&[("a", 3)], &[]), &[("a", 2)], &[("a", "S!A2")]);
        let d = diff(&old, &new);
        assert_eq!(d.regressions, vec!["a\ttext S!A2"]);
        assert_eq!(d.fixed, vec!["a\ttext S!A1"]);
        // More text cells in the case: new coverage, to be recorded, not a regression.
        let grown = with_text(b(&[("a", 3)], &[]), &[("a", 3)], &[("a", "S!A2")]);
        let d = diff(&old, &grown);
        assert!(d.regressions.is_empty());
        assert!(d.new_failures.contains(&"a\ttext S!A2".to_string()));
        assert!(d.is_dirty());
        // Text lines leave the value lists alone.
        assert_eq!(new.failing, BTreeSet::new());
    }

    /// `base` with pivot-layout counts and failures.
    fn with_layout(
        base: Baseline,
        checked: &[(&str, usize)],
        failing: &[(&str, &str)],
    ) -> Baseline {
        let t = with_text(Baseline::default(), checked, failing);
        Baseline {
            layout_checked: t.text_checked,
            layout_failing: t.text_failing,
            ..base
        }
    }

    #[test]
    fn pivot_layouts_ratchet_like_values() {
        // A pivot whose layout was Excel's in an unchanged case and now is not is a regression
        // even when every cell passes; one that now is Excel's is a fix (T-4944).
        let old = with_layout(b(&[("a", 3)], &[]), &[("a", 2)], &[("a", "K!Top")]);
        let new = with_layout(b(&[("a", 3)], &[]), &[("a", 2)], &[("a", "S!Pv")]);
        let d = diff(&old, &new);
        assert_eq!(d.regressions, vec!["a\tlayout S!Pv"]);
        assert_eq!(d.fixed, vec!["a\tlayout K!Top"]);
        // A case that now compares more pivots is new coverage, to be recorded.
        let grown = with_layout(b(&[("a", 3)], &[]), &[("a", 3)], &[("a", "S!Pv")]);
        let d = diff(&old, &grown);
        assert!(d.regressions.is_empty());
        assert!(d.new_failures.contains(&"a\tlayout S!Pv".to_string()));
        // A case new to the layout lines (an existing case once it compares them) is too.
        let d = diff(&b(&[("a", 3)], &[]), &new);
        assert!(d.regressions.is_empty());
        assert_eq!(d.new_cases, vec!["layout a"]);
        assert!(d.is_dirty());
        assert!(new.failing.is_empty() && new.text_failing.is_empty());
    }

    #[test]
    fn only_a_case_that_compares_its_pivot_lines_records_their_layout() {
        use crate::pivot_scoring::{LayoutVerdict, PivotLayout};
        let layout = |verdict| PivotLayout {
            sheet: "K".into(),
            name: "Top".into(),
            excel_location: "A3:D11".into(),
            engine_location: Some("A3:D11".into()),
            excel_lines: (7, 2),
            engine_lines: Some((7, 2)),
            verdict,
        };
        let export = |verdict| CaseResult {
            pivot_layout: vec![layout(verdict)],
            layout_checked: Some(2),
            ..CaseResult::for_test("x/a", "x")
        };
        let lines =
            Baseline::from_results(BaselineMode::Cells, &[&export(LayoutVerdict::LinesDiffer)]);
        assert_eq!(lines.layout_checked.get("x/a"), Some(&2));
        let items: Vec<_> = lines
            .layout_failing
            .iter()
            .map(|(_, i)| i.as_str())
            .collect();
        assert_eq!(items, ["K!Top"]);
        // A location verdict is the same item, so fixing the location alone changes nothing.
        let moved = Baseline::from_results(
            BaselineMode::Cells,
            &[&export(LayoutVerdict::LocationDiffers)],
        );
        assert!(!diff(&moved, &lines).is_dirty());
        // A case whose lines are not compared (every other suite) records no layout line.
        let other = CaseResult {
            pivot_layout: vec![layout(LayoutVerdict::LinesNotEmitted)],
            ..CaseResult::for_test("x/a", "x")
        };
        let plain = Baseline::from_results(BaselineMode::Cells, &[&other]);
        assert!(plain.layout_checked.is_empty() && plain.layout_failing.is_empty());
        // An ungated suite records nothing.
        let none =
            Baseline::from_results(BaselineMode::None, &[&export(LayoutVerdict::LinesDiffer)]);
        assert_eq!(none, Baseline::default());
    }

    #[test]
    fn classifies_regressions_new_failures_and_fixes() {
        let old = b(&[("a", 3), ("b", 2)], &[("a", "S!A1")]);
        let new = b(
            &[("a", 3), ("b", 3), ("c", 1)],
            &[("a", "S!A2"), ("b", "S!B1"), ("c", "S!C1")],
        );
        let d = diff(&old, &new);
        assert_eq!(d.regressions, vec!["a\tS!A2"]);
        assert!(d.new_failures.contains(&"b\tS!B1".to_string()));
        assert!(d.new_failures.contains(&"c\tS!C1".to_string()));
        assert_eq!(d.fixed, vec!["a\tS!A1"]);
        assert!(d.removed_cases.is_empty());
        assert_eq!(d.new_cases, vec!["c"]);
    }

    #[test]
    fn new_passing_case_makes_the_baseline_dirty() {
        // A case with no failures adds only its `C` line, which must still be recorded (T-1059).
        let old = b(&[("a", 3)], &[]);
        let new = b(&[("a", 3), ("b", 2)], &[]);
        let d = diff(&old, &new);
        assert_eq!(d.new_cases, vec!["b"]);
        assert!(d.new_failures.is_empty());
        assert!(d.is_dirty());
        assert!(!diff(&new, &new).is_dirty());
    }

    #[test]
    fn a_passing_case_records_its_failing_text_cells() {
        use crate::text_expect::TextResult;
        let text = |cell: &str, pass: bool| TextResult {
            sheet: "S".into(),
            cell: cell.into(),
            expected: "1".into(),
            actual: Some(if pass { "1" } else { "2" }.into()),
            pass,
        };
        let run = |pass: bool| CaseResult {
            text: vec![text("A1", true), text("A2", pass)],
            ..CaseResult::for_test("s/a", "s")
        };
        let before = run(true);
        let after = run(false);
        let old = Baseline::from_results(BaselineMode::Cells, &[&before]);
        let new = Baseline::from_results(BaselineMode::Cells, &[&after]);
        assert_eq!(new.text_checked.get("s/a"), Some(&2));
        assert!(new.failing.is_empty());
        // The check fails: the case's values all pass, yet one text cell regressed.
        assert_eq!(diff(&old, &new).regressions, vec!["s/a\ttext S!A2"]);
        // An ungated suite records nothing.
        assert_eq!(
            Baseline::from_results(BaselineMode::None, &[&after]),
            Baseline::default()
        );
    }

    #[test]
    fn roundtrips_through_disk() {
        let dir = std::env::temp_dir().join(format!("rs-baseline-{}", std::process::id()));
        let path = dir.join("x.txt");
        let base = with_text(
            b(&[("a", 3)], &[("a", "Sheet 1!A1")]),
            &[("a", 2)],
            &[("a", "Sheet 1!B2")],
        );
        let base = with_layout(base, &[("a", 1)], &[("a", "Sheet 1!Pivot 1")]);
        base.write(&path).unwrap();
        assert_eq!(Baseline::read(&path).unwrap(), base);
        let _ = std::fs::remove_dir_all(dir);
    }
}
