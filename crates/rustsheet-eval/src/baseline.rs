//! The no-regression ratchet ("known failures" baseline).
//!
//! `eval/baseline/<suite>.txt` records, for every case, how many cells it
//! checks, plus the exact list of items that are *known to fail*. The gate is:
//!
//! * any failing item that is **not** listed, in a case whose checked-cell count is
//!   unchanged, is a **regression** → CI fails;
//! * failing items in new or changed cases are **new coverage** → allowed, but must be
//!   recorded with `rustsheet-eval update-baseline`;
//! * listed items that now pass are **fixes** → ratchet them with `update-baseline`.
//! * a case missing from the baseline, even one that passes, is a **new case** → its
//!   checked-cell count must be recorded with `update-baseline`.
//!
//! The known-failure list doubles as the compatibility to-do list.
//!
//! Displayed text (decision 0068) is gated the same way on its own lines (decision 0070):
//! `TC<TAB>case<TAB>n` counts a case's scored text cells and `TF<TAB>case<TAB>Sheet!A1` lists
//! a known text failure, with the same regression, new-coverage and fix rules.
//!
//! A pivot's layout is gated the same way where the case compares it in full, location and
//! saved `rowItems`/`colItems` (an engine-export case, T-4944): `LC<TAB>case<TAB>n` counts the
//! case's sidecar pivots and `LF<TAB>case<TAB>Sheet!Pivot` lists a pivot whose layout is not
//! Excel's, whatever its [`crate::pivot_scoring::LayoutVerdict`]: a location fixed to reveal
//! wrong lines is no new failure. Any case whose pivots a saved package is compared for (the
//! round-trip goldens of SPEC-0033 X3, T-4180) can fill the same lines. The file header is left
//! as it was, so the new kinds rewrite only the baselines that hold them.
//!
//! Values ratchet against decision 0355's envelope (SPEC-0037 design 6), not each bit. `F` keeps
//! listing every bit-level known failure, Phase 1b's to-do list, and `E<TAB>case<TAB>item` lists
//! those of them outside the envelope: a cell [`cell_envelope`] calls `Outside` or `WrongType`,
//! and every whole-case item (`*`, `!status`), since a crashed or missing case is never drift. In
//! a `cases`-mode suite a case fails `*` only when one of its cells is outside. `W<TAB>case<TAB>item`
//! lists those `E` items that are a wrong type, error or text (`WrongType`), and every whole-case
//! item: decision 0355 item 6 blocks a cell with the right type going wrong even when it was
//! already outside as a number. In an unchanged case a new `E` or `W` item is a **regression**, a
//! new `F` item without an `E` item is **drift** (allowed, and recorded without
//! `--allow-regressions`), an item that leaves `E` but stays in `F` moved **into the envelope**,
//! and one that leaves `W` but stays in `E` is now the **right type** (both recorded like a fix).
//! A baseline written before the `E` kind (its header does not name it), and every round-trip
//! baseline, is judged as if each `F` item were an `E` and a `W` item, the bit-level rule it was
//! recorded under; one with `E` lines but written before the `W` kind as if each `E` item were a
//! `W` item.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::Path;

use anyhow::{Context, Result};

use crate::accuracy::envelope::{cell_envelope, CellEnvelope};
use crate::runner::{CaseResult, CaseStatus, CellResult};
use crate::suite::BaselineMode;

/// The header of a baseline without `E` lines: a round-trip baseline, or a cell baseline written
/// before decision 0355's envelope ratchet.
const HEADER: &str = "# RustSheet eval baseline (known failures). Generated by `rustsheet-eval update-baseline`;\n\
# never edit by hand. `C<TAB>case<TAB>checked-cells` lists every case; `F<TAB>case<TAB>item` lists\n\
# known failures. Removing an F line = a fix. Adding an F line to an unchanged case = a regression\n\
# and requires --allow-regressions plus a justification in the PR (docs/process/quality-gates.md).\n\
# `TC` and `TF` lines do the same for displayed text (decision 0070).\n";

/// The words of [`ENVELOPE_HEADER`] that mark a baseline as recording `E` lines.
const ENVELOPE_MARK: &str = "`E<TAB>case<TAB>item`";

/// The words of [`ENVELOPE_HEADER`] that mark a baseline as recording `W` lines.
const WRONG_TYPE_MARK: &str = "`W<TAB>case<TAB>item`";

/// The header of a cell baseline that records `E` and `W` lines (decision 0355 item 6).
const ENVELOPE_HEADER: &str = "# RustSheet eval baseline (known failures). Generated by `rustsheet-eval update-baseline`;\n\
# never edit by hand. `C<TAB>case<TAB>checked-cells` lists every case; `F<TAB>case<TAB>item` lists\n\
# every bit-level known failure, `E<TAB>case<TAB>item` those of them outside decision 0355's\n\
# envelope (a wrong type, error or text, a number off both 12 digits of Excel and the math, or a\n\
# whole case: `*`, `!status`), and `W<TAB>case<TAB>item` those of the E items that are a wrong\n\
# type, error or text, or a whole case. Removing an F line = a fix. In an unchanged case a new E\n\
# or W line = a regression and requires --allow-regressions plus a justification in the PR, while\n\
# a new F line without an E line is drift, recorded without it (docs/process/quality-gates.md).\n\
# `TC` and `TF` lines gate displayed text exactly (decision 0070).\n";

#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Baseline {
    /// case id → number of checked cells.
    pub checked: BTreeMap<String, usize>,
    /// (case id, item) known to fail. Item is `Sheet!A1`, `*` (whole case) or `!status`.
    pub failing: BTreeSet<(String, String)>,
    /// The items of `failing` outside decision 0355's envelope (`E` lines). Read only when
    /// `envelope` is set.
    pub outside: BTreeSet<(String, String)>,
    /// Whether the baseline records `E` lines. Without them (a round-trip baseline, or one
    /// written before the envelope ratchet) every `failing` item counts as outside.
    pub envelope: bool,
    /// The items of `outside` that are a wrong type, error or text, or a whole case (`W` lines).
    /// Read only when `typed` is set.
    pub wrong_type: BTreeSet<(String, String)>,
    /// Whether the baseline records `W` lines. Without them every outside item counts as a
    /// wrong type.
    pub typed: bool,
    /// case id → number of scored displayed-text cells (cases with none are absent).
    pub text_checked: BTreeMap<String, usize>,
    /// (case id, `Sheet!A1`) whose displayed text is known to fail.
    pub text_failing: BTreeSet<(String, String)>,
    /// case id → number of sidecar pivots whose layout is compared in full (cases with none are
    /// absent).
    pub layout_checked: BTreeMap<String, usize>,
    /// (case id, `Sheet!Pivot`) whose layout is known not to be Excel's.
    pub layout_failing: BTreeSet<(String, String)>,
}

impl Baseline {
    /// Builds the baseline describing `results`.
    #[must_use]
    pub fn from_results(mode: BaselineMode, results: &[&CaseResult]) -> Baseline {
        let mut b = Baseline::default();
        if mode == BaselineMode::None {
            return b;
        }
        b.envelope = true;
        b.typed = true;
        for r in results {
            if r.status == CaseStatus::Pending {
                continue;
            }
            b.checked.insert(r.id.clone(), r.checked);
            // Text is gated per cell whatever the value mode (decision 0070).
            if !r.text.is_empty() {
                b.text_checked.insert(r.id.clone(), r.text.len());
                for t in r.text.iter().filter(|t| !t.pass) {
                    b.text_failing
                        .insert((r.id.clone(), format!("{}!{}", t.sheet, t.cell)));
                }
            }
            // So is a fully compared pivot layout, whatever the value mode (T-4944).
            if let Some(n) = r.layout_checked.filter(|n| *n > 0) {
                b.layout_checked.insert(r.id.clone(), n);
                for p in &r.pivot_layout {
                    b.layout_failing
                        .insert((r.id.clone(), format!("{}!{}", p.sheet, p.name)));
                }
            }
            match r.status {
                CaseStatus::Pass | CaseStatus::Pending => {}
                CaseStatus::Fail if mode == BaselineMode::Cells => {
                    for c in r.cells.iter().filter(|c| c.verdict.is_failure()) {
                        b.add_failing(&r.id, c.key(), cell_envelope(c));
                    }
                }
                // A corpus case with only drift is no failure (SPEC-0037 design 6).
                CaseStatus::Fail => {
                    if r.cells.iter().any(outside_envelope) {
                        b.add_failing(&r.id, "*".into(), CellEnvelope::WrongType);
                    }
                }
                other => b.add_failing(&r.id, format!("!{other:?}"), CellEnvelope::WrongType),
            }
        }
        b
    }

    /// Records `item` of `case` as a known failure of class `class`: an `E` item unless it is
    /// inside the envelope, and a `W` item too when it is a wrong type. A whole-case item is
    /// recorded as a wrong type: a crashed or missing case is never drift.
    fn add_failing(&mut self, case: &str, item: String, class: CellEnvelope) {
        let key = (case.to_string(), item);
        if class == CellEnvelope::WrongType {
            self.wrong_type.insert(key.clone());
        }
        if class != CellEnvelope::Inside {
            self.outside.insert(key.clone());
        }
        self.failing.insert(key);
    }

    /// The known failures outside the envelope: the `E` items, or every `F` item of a baseline
    /// without `E` lines.
    #[must_use]
    pub fn outside_items(&self) -> &BTreeSet<(String, String)> {
        if self.envelope {
            &self.outside
        } else {
            &self.failing
        }
    }

    /// The known failures that are a wrong type, error or text, or a whole case: the `W` items,
    /// or every outside item ([`Baseline::outside_items`]) of a baseline without `W` lines.
    #[must_use]
    pub fn wrong_type_items(&self) -> &BTreeSet<(String, String)> {
        if self.typed {
            &self.wrong_type
        } else {
            self.outside_items()
        }
    }

    /// Reads a baseline file; a missing file is an empty baseline.
    ///
    /// # Errors
    /// Fails if the file exists but cannot be read or parsed.
    pub fn read(path: &Path) -> Result<Baseline> {
        let mut b = Baseline::default();
        if !path.exists() {
            return Ok(b);
        }
        let text = std::fs::read_to_string(path).with_context(|| path.display().to_string())?;
        for (n, line) in text.lines().enumerate() {
            if line.starts_with('#') {
                b.envelope |= line.contains(ENVELOPE_MARK);
                b.typed |= line.contains(WRONG_TYPE_MARK);
                continue;
            }
            if line.trim().is_empty() {
                continue;
            }
            let mut parts = line.splitn(3, '\t');
            let count = |cells: &str| -> Result<usize> {
                cells
                    .parse()
                    .with_context(|| format!("{}:{}: bad count", path.display(), n + 1))
            };
            match (parts.next(), parts.next(), parts.next()) {
                (Some("C"), Some(case), Some(cells)) => {
                    b.checked.insert(case.to_string(), count(cells)?);
                }
                (Some("F"), Some(case), Some(item)) => {
                    b.failing.insert((case.to_string(), item.to_string()));
                }
                (Some("E"), Some(case), Some(item)) => {
                    b.envelope = true;
                    b.outside.insert((case.to_string(), item.to_string()));
                }
                (Some("W"), Some(case), Some(item)) => {
                    b.typed = true;
                    b.wrong_type.insert((case.to_string(), item.to_string()));
                }
                (Some("TC"), Some(case), Some(cells)) => {
                    b.text_checked.insert(case.to_string(), count(cells)?);
                }
                (Some("TF"), Some(case), Some(item)) => {
                    b.text_failing.insert((case.to_string(), item.to_string()));
                }
                (Some("LC"), Some(case), Some(pivots)) => {
                    b.layout_checked.insert(case.to_string(), count(pivots)?);
                }
                (Some("LF"), Some(case), Some(item)) => {
                    b.layout_failing
                        .insert((case.to_string(), item.to_string()));
                }
                _ => anyhow::bail!("{}:{}: malformed line", path.display(), n + 1),
            }
        }
        Ok(b)
    }

    /// Writes the baseline deterministically.
    ///
    /// # Errors
    /// Fails if the file cannot be written.
    pub fn write(&self, path: &Path) -> Result<()> {
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        let mut out = String::from(if self.envelope {
            ENVELOPE_HEADER
        } else {
            HEADER
        });
        for (case, count) in &self.checked {
            let _ = writeln!(out, "C\t{case}\t{count}");
        }
        for (case, item) in &self.failing {
            let _ = writeln!(out, "F\t{case}\t{item}");
        }
        if self.envelope {
            for (case, item) in &self.outside {
                let _ = writeln!(out, "E\t{case}\t{item}");
            }
            // A baseline read without `W` lines writes each `E` item as one: the rule it was
            // judged under.
            for (case, item) in self.wrong_type_items() {
                let _ = writeln!(out, "W\t{case}\t{item}");
            }
        }
        for (case, count) in &self.text_checked {
            let _ = writeln!(out, "TC\t{case}\t{count}");
        }
        for (case, item) in &self.text_failing {
            let _ = writeln!(out, "TF\t{case}\t{item}");
        }
        for (case, count) in &self.layout_checked {
            let _ = writeln!(out, "LC\t{case}\t{count}");
        }
        for (case, item) in &self.layout_failing {
            let _ = writeln!(out, "LF\t{case}\t{item}");
        }
        std::fs::write(path, out).with_context(|| path.display().to_string())
    }
}

/// Whether scored cell `c` is outside decision 0355's envelope ([`cell_envelope`] calls it
/// `Outside` or `WrongType`): an `E` item when it fails, and a cell the visible-parity lock counts.
#[must_use]
pub fn outside_envelope(c: &CellResult) -> bool {
    cell_envelope(c) != CellEnvelope::Inside
}

#[derive(Debug, Default)]
pub struct Delta {
    /// Items newly outside the envelope or newly a wrong type (new `E` or `W` items) in cases
    /// whose checked-cell count did not change.
    pub regressions: Vec<String>,
    /// Items newly failing inside the envelope (new `F` items without an `E` item) in cases
    /// whose checked-cell count did not change: allowed, but must be recorded (decision 0355
    /// item 6).
    pub drift: Vec<String>,
    /// Failing items in new or changed cases (allowed; must be recorded).
    pub new_failures: Vec<String>,
    /// Previously failing items that now pass.
    pub fixed: Vec<String>,
    /// Items that were outside the envelope and still fail, now inside it (recorded like a fix).
    pub into_envelope: Vec<String>,
    /// Items that were a wrong type and are still outside the envelope, now the right type (a
    /// number off Excel; recorded like a fix).
    pub right_type: Vec<String>,
    /// Cases present in the baseline but absent now.
    pub removed_cases: Vec<String>,
    /// Cases absent from the baseline but run now, passing or not: their `C` line must be
    /// recorded (docs/process/quality-gates.md, T-1059).
    pub new_cases: Vec<String>,
}

impl Delta {
    /// Whether the baseline file would change.
    #[must_use]
    pub fn is_dirty(&self) -> bool {
        !(self.regressions.is_empty()
            && self.drift.is_empty()
            && self.new_failures.is_empty()
            && self.fixed.is_empty()
            && self.into_envelope.is_empty()
            && self.right_type.is_empty()
            && self.removed_cases.is_empty()
            && self.new_cases.is_empty())
    }
}

/// One suite's summary lines for `check` and `update-baseline`: its counts, then each
/// regression and drift item (decision 0355 item 6), at most 25 of each.
#[must_use]
pub fn summary(name: &str, old: &Baseline, current: &Baseline, delta: &Delta) -> Vec<String> {
    let mut lines = vec![format!(
        "[{name}] known failures {} -> {} ({} -> {} outside the envelope, {} -> {} wrong type), text {} -> {}, layout {} -> {}  (fixed {}, into envelope {}, right type {}, drift {}, new-coverage failures {}, REGRESSIONS {}, new cases {}, removed cases {})",
        old.failing.len(),
        current.failing.len(),
        old.outside_items().len(),
        current.outside_items().len(),
        old.wrong_type_items().len(),
        current.wrong_type_items().len(),
        old.text_failing.len(),
        current.text_failing.len(),
        old.layout_failing.len(),
        current.layout_failing.len(),
        delta.fixed.len(),
        delta.into_envelope.len(),
        delta.right_type.len(),
        delta.drift.len(),
        delta.new_failures.len(),
        delta.regressions.len(),
        delta.new_cases.len(),
        delta.removed_cases.len()
    )];
    lines.extend(
        delta
            .regressions
            .iter()
            .take(25)
            .map(|r| format!("  REGRESSION {r}")),
    );
    // Drift is allowed, but each item is shown: the baseline's diff carries all of them.
    lines.extend(
        delta
            .drift
            .iter()
            .take(25)
            .map(|d| format!("  drift {}", d.replacen('\t', " ", 1))),
    );
    if delta.drift.len() > 25 {
        lines.push(format!(
            "  ... and {} more drift items (the baseline's diff lists them)",
            delta.drift.len() - 25
        ));
    }
    lines
}

/// Compares the committed baseline with the current run: values against the envelope, then
/// displayed text, whose labels carry a `text ` prefix on the item (decision 0070), then pivot
/// layouts, `layout ` (T-4944). Text and layout are exact: every failure of theirs is outside.
#[must_use]
pub fn diff(old: &Baseline, new: &Baseline) -> Delta {
    let mut d = Delta::default();
    diff_items(
        Side::new(
            &old.checked,
            &old.failing,
            old.outside_items(),
            old.wrong_type_items(),
        ),
        Side::new(
            &new.checked,
            &new.failing,
            new.outside_items(),
            new.wrong_type_items(),
        ),
        "",
        &mut d,
    );
    diff_items(
        Side::exact(&old.text_checked, &old.text_failing),
        Side::exact(&new.text_checked, &new.text_failing),
        "text ",
        &mut d,
    );
    diff_items(
        Side::exact(&old.layout_checked, &old.layout_failing),
        Side::exact(&new.layout_checked, &new.layout_failing),
        "layout ",
        &mut d,
    );
    d
}

type Items = BTreeSet<(String, String)>;

/// One baseline's checked counts, failing items, items outside the envelope and wrong-type
/// items, for one ratchet.
#[derive(Clone, Copy)]
struct Side<'a> {
    checked: &'a BTreeMap<String, usize>,
    failing: &'a Items,
    outside: &'a Items,
    wrong_type: &'a Items,
}

impl<'a> Side<'a> {
    fn new(
        checked: &'a BTreeMap<String, usize>,
        failing: &'a Items,
        outside: &'a Items,
        wrong_type: &'a Items,
    ) -> Self {
        Side {
            checked,
            failing,
            outside,
            wrong_type,
        }
    }

    /// A ratchet with no envelope: every failing item is outside and a wrong type.
    fn exact(checked: &'a BTreeMap<String, usize>, failing: &'a Items) -> Self {
        Side::new(checked, failing, failing, failing)
    }
}

/// One ratchet of `old` against `new`; `prefix` marks the items' labels.
fn diff_items(old: Side<'_>, new: Side<'_>, prefix: &str, d: &mut Delta) {
    let unchanged = |case: &str| {
        old.checked.contains_key(case) && old.checked.get(case) == new.checked.get(case)
    };
    let label = |case: &str, item: &str| format!("{case}\t{prefix}{item}");
    // New `F`, `E` and `W` items, each once: an item that drifted before and now leaves the
    // envelope, or was outside as a number and is now a wrong type, is a regression only.
    let newly: BTreeSet<&(String, String)> = new
        .failing
        .difference(old.failing)
        .chain(new.outside.difference(old.outside))
        .chain(new.wrong_type.difference(old.wrong_type))
        .collect();
    for key in newly {
        let (case, item) = key;
        let worse = (new.outside.contains(key) && !old.outside.contains(key))
            || (new.wrong_type.contains(key) && !old.wrong_type.contains(key));
        match (unchanged(case), worse) {
            (true, true) => d.regressions.push(label(case, item)),
            (true, false) => d.drift.push(label(case, item)),
            (false, _) => d.new_failures.push(label(case, item)),
        }
    }
    for (case, item) in old.failing.difference(new.failing) {
        if new.checked.contains_key(case) {
            d.fixed.push(label(case, item));
        }
    }
    for key in old.outside.difference(new.outside) {
        let (case, item) = key;
        if new.checked.contains_key(case) && new.failing.contains(key) {
            d.into_envelope.push(label(case, item));
        }
    }
    for key in old.wrong_type.difference(new.wrong_type) {
        let (case, item) = key;
        if new.checked.contains_key(case) && new.outside.contains(key) {
            d.right_type.push(label(case, item));
        }
    }
    for case in old.checked.keys() {
        if !new.checked.contains_key(case) {
            d.removed_cases.push(format!("{prefix}{case}"));
        }
    }
    for case in new.checked.keys() {
        if !old.checked.contains_key(case) {
            d.new_cases.push(format!("{prefix}{case}"));
        }
    }
    d.new_failures.extend(
        new.checked
            .iter()
            .filter(|(c, n)| old.checked.get(*c).is_some_and(|o| o != *n))
            .map(|(c, n)| format!("{c}\t({prefix}checked cells changed to {n})")),
    );
}

