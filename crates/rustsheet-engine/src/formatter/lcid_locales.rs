/// Whether `lcid` names a locale in Excel (language 0 excepted, which is not in the table).
pub(super) fn has_locale(lcid: u16) -> bool {
    let language = usize::from(lcid & 0x3FF);
    let sublanguage = lcid >> 10;
    SUBLANGUAGES
        .get(language)
        .is_some_and(|mask| mask >> sublanguage & 1 == 1)
}

#[cfg(test)]
mod tests {
    use super::has_locale;

    #[test]
    fn probed_lcids() {
        // probes/t3666-lcid-sublanguage-sweep: en-NZ and en-AE have a locale, 0x5009 none; Korean
        // only 0x12, 0x412 and 0xF412-0xFC12; ga-IE 0x83C, not 0x43C.
        for lcid in [0x409, 0x1409, 0x4C09, 0xF409, 0x412, 0xF412, 0x83C, 0x7C04] {
            assert!(has_locale(lcid), "{lcid:X}");
        }
        for lcid in [0x1, 0x5009, 0x812, 0x2412, 0x43C, 0x2407, 0x3FF] {
            assert!(!has_locale(lcid), "{lcid:X}");
        }
    }
}
