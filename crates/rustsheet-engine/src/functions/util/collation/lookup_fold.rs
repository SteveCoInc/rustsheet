/// - a supplementary character is itself: Deseret, Osage, Adlam and the other astral scripts stay
///   apart from their other case (probes/t3298-case-mapping-sweep Calc!C38:D48);
/// - a member of one of Excel's wider classes is the class's first member ([`CLASSES`]);
/// - otherwise SEARCH's [`fold_char`], unless that lands on a weightless character or `c` is in
///   [`APART`]: then `c` stays itself, so Cherokee's capitals U+13A0-U+13EF (whose small letters
///   U+AB70-U+ABBF are weightless) equal only themselves (Calc!C18:D19).
pub(crate) fn fold_lookup_char(c: char) -> char {
    if is_weightless(c) {
        return WEIGHTLESS;
    }
    if u16::try_from(u32::from(c)).is_err() {
        return c;
    }
    let folded = fold_char(c);
    if is_weightless(folded) || APART.contains(&c) {
        return c;
    }
    class_first(c)
        .or_else(|| class_first(folded))
        .unwrap_or(folded)
}

/// The first member of `c`'s class in [`CLASSES`], if it is in one. The collation's `=` equates
/// the members the same way (`super::fold`, T-4013).
pub(super) fn class_first(c: char) -> Option<char> {
    let unit = u16::try_from(u32::from(c)).ok()?;
    let index = CLASSES
        .binary_search_by_key(&unit, |&(member, _)| member)
        .ok()?;
    CLASSES
        .get(index)
        .and_then(|&(_, first)| char::from_u32(u32::from(first)))
}

/// [`fold_lookup_char`] over `text`, one character to one. Past the run's allowance it is the
/// empty text without reading `text` (`compared::out_of_ticks`, T-4278).
pub(crate) fn fold_lookup(text: &str) -> String {
    if super::out_of_ticks() {
        return String::new();
    }
    super::note_compared(text.len(), super::FOLD_TICKS);
    text.chars().map(fold_lookup_char).collect()
}

#[cfg(test)]
mod tests {
    use super::{fold_lookup, fold_lookup_char, WEIGHTLESS, WEIGHTLESS_RANGES};

    /// One character per class of the block table (probes/t3298-case-mapping-sweep,
    /// probes/t3584-match-fold-weightless).
    #[test]
    fn folds_like_excels_comparison_table() {
        // Folds as Rust's simple lowercase: Latin, Cyrillic, Glagolitic, Georgian Asomtavruli.
        for (upper, lower) in [
            ('A', 'a'),
            ('Ж', 'ж'),
            ('\u{2c00}', '\u{2c30}'),
            ('\u{10a0}', '\u{2d00}'),
        ] {
            assert_eq!(fold_lookup_char(upper), fold_lookup_char(lower), "{upper}");
        }
        // Stays apart: the astral scripts (Deseret), Cherokee's capitals, Ɒ and Ɥ, ϐ against β.
        for (upper, lower) in [
            ('\u{10400}', '\u{10428}'),
            ('\u{13a0}', '\u{ab70}'),
            ('\u{2c70}', '\u{252}'),
            ('\u{a78d}', '\u{265}'),
            ('\u{3d0}', 'β'),
        ] {
            assert_ne!(fold_lookup_char(upper), fold_lookup_char(lower), "{upper}");
        }
        // The wider classes: ϳ with Ͷ, ϵ with Ε, ϴ with ϑ and not θ, U+1FBE with Ι, the Greek
        // Extended psili+varia and dasia+oxia letters, Ꝯ with ꝰ, U+10FA with გ.
        for (a, b) in [
            ('\u{3f3}', '\u{376}'),
            ('\u{3f5}', 'Ε'),
            ('\u{3f4}', '\u{3d1}'),
            ('\u{1fbe}', 'Ι'),
            ('\u{1f0d}', '\u{1f02}'),
            ('\u{a770}', '\u{a76e}'),
            ('\u{10fa}', '\u{10d2}'),
        ] {
            assert_eq!(fold_lookup_char(a), fold_lookup_char(b), "{a}");
        }
        assert_ne!(fold_lookup_char('\u{3f4}'), fold_lookup_char('θ'));
    }

    /// Weightless characters are one class, apart from everything weighted and one unit long:
    /// U+0524 with U+10C7, U+AB70 with U+1C90, the soft hyphen with U+0378 (Calc!B1:H18).
    #[test]
    fn weightless_characters_are_one_class() {
        for c in [
            '\u{524}', '\u{10c7}', '\u{ab70}', '\u{1c90}', '\u{ad}', '\u{378}', '\u{feff}',
        ] {
            assert_eq!(fold_lookup_char(c), WEIGHTLESS, "{c:?}");
        }
        for c in ['\u{526}', '\u{200b}', '\u{e000}', '\u{10400}', 'a'] {
            assert_ne!(fold_lookup_char(c), WEIGHTLESS, "{c:?}");
        }
        assert_eq!(fold_lookup("a\u{524}b").chars().count(), 3);
        assert_eq!(
            WEIGHTLESS_RANGES
                .iter()
                .map(|&(a, b)| u32::from(b - a) + 1)
                .sum::<u32>(),
            2568
        );
        assert!(WEIGHTLESS_RANGES.windows(2).all(|w| w[0].1 < w[1].0));
    }
}
